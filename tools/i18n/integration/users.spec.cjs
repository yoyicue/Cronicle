const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const { labs, localPage, login, logout, route, api, admin, action, canonical, equalBuilds, eventFixture } = require('./helpers.cjs');
const password = 'LocalOnly!StrongPass2026';
test('I02 I27 I28 user creation, account update, recovery mail and privilege refusal remain equivalent', async ({ browser }, info) => {
  test.setTimeout(90000);
  const traces = [];
  for (const lab of labs()) {
    const username = 'reader' + info.project.name, email = username + '@invalid.test';
    const session = await admin(lab);
    const { page, context, errors } = await localPage(browser, lab);
    await login(page);
    await route(page, 'Admin?sub=new_user');
    await page.fill('#fe_eu_username', username);
    await page.fill('#fe_eu_email', email);
    await page.fill('#fe_eu_fullname', 'History Success');
    await page.fill('#fe_eu_password', password);
    await page.uncheck('#fe_eu_priv_admin');
    await page.uncheck('#fe_eu_priv_run_events');
    const create = await action(page, '$P().do_new_user()', 'user/admin_create');
    expect(create.body).toMatchObject({ username, full_name: 'History Success', password, send_email: 1 });
    expect(create.body.privileges.admin).toBe(0);
    await expect(page.locator('#fe_eu_username')).toBeDisabled();
    await page.fill('#fe_eu_fullname', 'Home Run 每日');
    const update = await action(page, '$P().do_save_user()', 'user/admin_update');
    await logout(page);
    await login(page, username, password);
    expect(await page.evaluate(() => app.user.privileges.admin)).toBe(0);
    const lowSession = await page.evaluate(() => app.getPref('session_id'));
    const denied = await api(lab, 'app/create_api_key', { title: 'forbidden' }, lowSession);
    expect(denied.code).not.toBe(0);
    const noSession = await api(lab, 'app/get_schedule');
    expect(noSession.code).not.toBe(0);
    const fixtureId = 'forbidden' + info.project.name;
    await api(lab, 'app/create_event', eventFixture(fixtureId), session);
    const noRun = await api(lab, 'app/run_event', { id: fixtureId }, lowSession);
    expect(noRun.code).not.toBe(0);
    expect((await api(lab, 'app/delete_event', { id: fixtureId }, session)).code).toBe(0);
    await route(page, 'MyAccount');
    await page.fill('#fe_ma_fullname', 'History Run');
    await page.fill('#fe_ma_old_password', password);
    const account = await action(page, '$P().save_changes()', 'user/update');
    expect(account.body.full_name).toBe('History Run');
    await logout(page);
    await expect(page.locator('#fe_login_username')).toBeVisible();
    await page.fill('#fe_login_username', username); await page.fill('#fe_login_password', 'wrong');
    const invalidResponse = page.waitForResponse(r => r.url().endsWith('/user/login') && r.request().method() === 'POST');
    await page.locator('[onmouseup="$P().doLogin()"]').dispatchEvent('mouseup');
    const invalid = await (await invalidResponse).json();
    expect(invalid.code).not.toBe(0);
    await expect(page.locator('body')).toContainText(invalid.description);
    await route(page, 'Login?recover=1');
    await page.fill('#fe_pr_username', username); await page.fill('#fe_pr_email', email);
    const recover = await action(page, '$P().doSendRecoveryEmail()', 'user/forgot_password');
    let decoded;
    // All three origins share a recipient; wait for this origin's recovery mail, not an earlier origin's count.
    await expect.poll(() => {
      decoded = JSON.parse(fs.readFileSync(path.join(__dirname, '../out/smtp.json')))
        .map(mail => mail.replace(/=\r\n/g, '').replace(/=([A-F\d]{2})/g, (_, hex) => String.fromCharCode(parseInt(hex, 16))))
        .find(mail => mail.includes(email) && mail.includes(lab.baseURL + '/') && mail.includes('Login?u=' + username + '&h='));
      return Boolean(decoded);
    }).toBe(true);
    const token = decoded.match(/Login\?u=([^&\s]+)&h=(\w+)/);
    expect(token[1]).toBe(username);
    await route(page, 'Login?u=' + username + '&h=' + token[2]);
    const newPassword = password + 'More!29';
    await page.fill('#fe_reset_password', newPassword);
    await page.waitForFunction(() => typeof window.zxcvbn === 'function');
    await page.locator('#fe_reset_password').press('End');
    await page.waitForFunction(() => app.last_password_strength && app.last_password_strength.score >= 3);
    const reset = await action(page, '$P().doResetPassword()', 'user/reset_password');
    expect(reset.body.key).toBe(token[2]);
    expect(reset.body.new_password).toBe(newPassword);
    reset.body.key = '<token-from-local-recovery-mail>';
    await expect(page.locator('#fe_login_username')).toBeVisible();
    await login(page, username, newPassword);
    await logout(page);
    await login(page);
    await route(page, 'Admin?sub=edit_user&username=' + username);
    await page.locator('[onmouseup="$P().show_delete_account_dialog()"]:visible').dispatchEvent('mouseup');
    const remove = await action(page, 'app.confirm_click(true)', 'user/admin_delete');
    traces.push([canonical(create.body), canonical(update.body), canonical(account.body), canonical(recover.body), canonical(reset.body), canonical(remove.body), denied, noSession, noRun, invalid]);
    expect(errors).toEqual([]);
    await context.close();
  }
  equalBuilds(traces);
});
